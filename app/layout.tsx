import type { Metadata } from "next";
import type { CSSProperties } from "react";
import { getBrandIconColor } from "@/lib/environment";
import { Geist, Geist_Mono } from "next/font/google";
import { getNavigation } from "@/lib/navigation/get-navigation";
import { NavigationShell } from "@/components/navigation-shell";
import { SessionActivity } from "@/components/session-activity";
import { UnsavedChangesGuard } from "@/components/unsaved-changes";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Veranstaltungsverwaltung",
  description: "Generated by create next app",
  icons: { icon: { url: "/icon.svg", type: "image/svg+xml" } },
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
  // A database outage must not prevent the public status page from rendering.
  // Protected pages still enforce their own authorization.
  const navigation = await getNavigation().catch(() => null);
  return (
    <html
      lang="de"
      style={{ "--brand-icon-background": getBrandIconColor() } as CSSProperties}
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <UnsavedChangesGuard />
        {navigation && <SessionActivity />}
        {navigation ? <NavigationShell data={navigation}>{children}</NavigationShell> : children}
      </body>
    </html>
  );
}
